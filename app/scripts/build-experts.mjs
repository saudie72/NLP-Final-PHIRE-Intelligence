// Bundles the chat experts for the Netlify Function at build time: each agent's instructions from
// .claude/agents/<id>.md plus every file in knowledge/<id>/. Pushing a new knowledge document and
// redeploying updates what the experts know. Output: netlify/lib/experts-data.mjs (git-ignored). It must stay
// outside netlify/functions/, where Netlify treats every file as a separate function.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("../../", import.meta.url);
export const CHAT_EXPERTS = ["erp-functional-analyst", "erp-developer", "peoplesoft-admin", "erp-manager", "erp-business-analyst", "orchestrator"];

const experts = {};
for (const id of CHAT_EXPERTS) {
  const text = readFileSync(new URL(`.claude/agents/${id}.md`, ROOT), "utf8");
  const end = text.indexOf("\n---", 4);
  const body = text.slice(end + 4)
    // tool instructions don't apply in chat: knowledge files are included below instead
    .replace(/^> \*\*Mandatory first action:\*\*[\s\S]*?\n\n/m, "")
    .trim();
  const title = (body.match(/^# (.+)$/m) || [])[1] || id;
  const name = (body.match(/\*\*Your name is (\w+)\.\*\*/) || [])[1] || title;
  const dir = new URL(`knowledge/${id}/`, ROOT);
  const knowledge = existsSync(dir)
    ? readdirSync(dir).filter((f) => f.endsWith(".md") && f !== "README.md").sort()
        .map((f) => ({ file: `knowledge/${id}/${f}`, text: readFileSync(new URL(f, dir), "utf8") }))
    : [];
  experts[id] = { id, name, role: title, prompt: body, knowledge };
}
const out = new URL("../netlify/lib/experts-data.mjs", import.meta.url);
mkdirSync(new URL("../netlify/lib/", import.meta.url), { recursive: true });
writeFileSync(out, `// Generated by scripts/build-experts.mjs. Do not edit.\nexport default ${JSON.stringify(experts, null, 1)};\n`);
console.log(`bundled ${CHAT_EXPERTS.length} experts (${Object.values(experts).reduce((n, e) => n + e.knowledge.length, 0)} knowledge files)`);
